    // Phrases indexed by their first character: at each position the converter
    // only looks at the bucket for that character instead of scanning the whole
    // table. The table is generated longest-source-first, so the first match in a
    // bucket is the longest one.
    var PHRASES_BY_FIRST = {};
    for (var pi = 0; pi < S2T_PHRASES.length; pi++) {
      var pfirst = S2T_PHRASES[pi][0].charAt(0);
      if (PHRASES_BY_FIRST[pfirst] === undefined) PHRASES_BY_FIRST[pfirst] = [];
      PHRASES_BY_FIRST[pfirst].push(S2T_PHRASES[pi]);
    }

    // One left-to-right pass, longest phrase first at each position.
    //
    // The earlier version applied every phrase as a global replacement in
    // sequence, which let one phrase rewrite the *output* of another:
    // 客户端 -> 用戶端 -> 使用者端, because 用戶→使用者 fired on the finished
    // result. Single-pass matching consumes the source text, so a replacement can
    // never feed the next phrase, and the result is what a reader expects.
    function convertS2T(text) {
      if (typeof text !== "string" || text.length === 0) return text;
      var out = "";
      var i = 0;
      while (i < text.length) {
        var bucket = PHRASES_BY_FIRST[text.charAt(i)];
        var hit = null;
        if (bucket !== undefined) {
          for (var k = 0; k < bucket.length; k++) {
            if (text.substr(i, bucket[k][0].length) === bucket[k][0]) { hit = bucket[k]; break; }
          }
        }
        if (hit !== null) {
          out += hit[1];
          i += hit[0].length;
          continue;
        }
        var ch = text.charAt(i);
        out += (S2T_CHARS[ch] !== undefined ? S2T_CHARS[ch] : ch);
        i += 1;
      }
      return out;
    }

    // === zh-TW choice persistence ===
    // The framework's `locale.preference` schema only accepts 'zh'/'en', so
    // `host.set('preference', 'zh-TW')` is rejected by the host and the choice
    // is never saved. On restart the async settings mirror then calls adopt(),
    // which re-applies the persisted preference (or the browser language) and
    // overrides the zh-TW forced at plugin boot -- hence the user must re-select
    // Traditional Chinese after every restart. Fix: record the choice in
    // localStorage and re-assert zh-TW after adopt() unless the user explicitly
    // picked zh/en (which the framework itself persists).
    var STORAGE_KEY = "zhtw-traditional-chinese:preference";

    function readStoredChoice() {
      try {
        if (typeof localStorage === "undefined") return null;
        return localStorage.getItem(STORAGE_KEY);
      } catch (e) {
        return null;
      }
    }

    function writeStoredChoice(id) {
      try {
        if (typeof localStorage === "undefined") return;
        localStorage.setItem(STORAGE_KEY, id);
      } catch (e) {}
    }

